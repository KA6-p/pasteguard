#!/usr/bin/env node
/**
 * Regenerates src/popularPackages.ts from real download statistics (hugovk/top-pypi-packages).
 *
 * Usage:  npm run update-popular            (top 5000)
 *         node scripts/updatePopular.js 2000
 *
 * NOTE: written without network access to the dataset, so the JSON shape handling below is defensive.
 * If it fails, it prints what it received. Your hand-curated starter list keeps working either way.
 */
const fs = require("node:fs");
const path = require("node:path");

const URLS = [
  "https://hugovk.github.io/top-pypi-packages/top-pypi-packages.min.json",
  "https://hugovk.github.io/top-pypi-packages/top-pypi-packages-30-days.min.json",
];
const limit = Number(process.argv[2]) || 5000;
const normalize = (n) => String(n).toLowerCase().replace(/[-_.]+/g, "-");

async function fetchJson() {
  for (const url of URLS) {
    try {
      const res = await fetch(url, { headers: { "User-Agent": "PasteGuard-update-popular" } });
      if (res.ok) {
        console.log("Fetched", url);
        return await res.json();
      }
      console.warn(`${url} -> HTTP ${res.status}`);
    } catch (err) {
      console.warn(`${url} -> ${err.message}`);
    }
  }
  throw new Error("Could not download the top packages dataset.");
}

(async () => {
  const data = await fetchJson();
  const rows = Array.isArray(data) ? data : data.rows;
  if (!Array.isArray(rows)) {
    throw new Error("Unexpected JSON shape. Top-level keys: " + Object.keys(data).join(", "));
  }
  const names = [];
  const seen = new Set();
  for (const r of rows) {
    const raw = typeof r === "string" ? r : r && (r.project || r.name);
    if (!raw) continue;
    const n = normalize(raw);
    if (/^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?$/.test(n) && !seen.has(n)) {
      seen.add(n);
      names.push(n);
    }
    if (names.length >= limit) break;
  }
  if (names.length < 100) {
    throw new Error(`Only ${names.length} usable names found; refusing to overwrite the list.`);
  }
  const body = names.map((n) => `  "${n}"`).join(",\n");
  const out = `/**
 * Popular PyPI package names (PEP 503 normalized), most popular first.
 * GENERATED by scripts/updatePopular.js on ${new Date().toISOString().slice(0, 10)} from hugovk/top-pypi-packages.
 * Used only for lookalike detection and "did you mean" suggestions, never to decide a package is safe.
 */
export const POPULAR_PACKAGES: readonly string[] = [
${body},
];
`;
  fs.writeFileSync(path.join(__dirname, "..", "src", "popularPackages.ts"), out);
  console.log(`Wrote ${names.length} package names to src/popularPackages.ts`);
})().catch((e) => {
  console.error("update-popular failed:", e.message);
  process.exit(1);
});
